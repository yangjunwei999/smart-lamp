static uint32_t TimClkHz(void)
{
  uint32_t pclk1 = HAL_RCC_GetPCLK1Freq();
  if ((RCC->CFGR & RCC_CFGR_PPRE1) == RCC_HCLK_DIV1)
  {
    return pclk1;
  }
  return pclk1 * 2U;
}
